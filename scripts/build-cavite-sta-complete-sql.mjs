/**
 * Concatenate migration + seed into one file for Supabase SQL Editor.
 * Run: node scripts/build-cavite-sta-complete-sql.mjs
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const migDir = join(root, 'supabase', 'migrations');
const seedPath = join(root, 'supabase', 'seed_cavite_lgu_establishments.sql');
const outPath = join(root, 'supabase', 'cavite_sta_v3_FULL_for_sql_editor.sql');

const migrations = readdirSync(migDir)
  .filter((f) => f.includes('cavite_lgu_establishments') && f.endsWith('.sql'))
  .sort()
  .reverse();
if (!migrations.length) {
  console.error('No cavite_lgu_establishments migration found.');
  process.exit(1);
}
const migPath = join(migDir, migrations[0]);

const header = `-- =============================================================================
-- CaviTour — STA-v3 Cavite 2025 (FULL: schema + data)
-- Generated by build-cavite-sta-complete-sql.mjs — paste into Supabase SQL Editor, Run once
-- Maps & apps use: public.v_cavite_establishments
-- =============================================================================

`;

let body = readFileSync(migPath, 'utf8');
if (existsSync(seedPath)) {
  body += '\n\n' + readFileSync(seedPath, 'utf8');
} else {
  body += '\n-- WARNING: seed file missing. Run: npm run cavite:seed\n';
}

writeFileSync(outPath, header + body, 'utf8');
console.log('Wrote', outPath);
