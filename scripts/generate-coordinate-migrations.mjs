/**
 * Build Supabase SQL migrations from geocoded JSON files.
 * Run after: node scripts/geocode-cavite-coordinates.mjs
 */
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

function esc(s) {
  return String(s ?? '').replace(/'/g, "''");
}

const terminals = JSON.parse(
  readFileSync(join(root, 'data', 'cavite_terminals_geocoded.json'), 'utf8')
);
const establishments = JSON.parse(
  readFileSync(join(root, 'data', 'cavite_sta_v3_geocoded.json'), 'utf8')
);

const ts = '20260520120000';

const terminalLines = [
  `-- Accurate WGS84 coordinates for cavitour_terminals (Google Maps / OSM compatible)`,
  `-- Generated by scripts/generate-coordinate-migrations.mjs`,
  ``,
  `ALTER TABLE public.cavitour_terminals`,
  `  ADD COLUMN IF NOT EXISTS latitude double precision,`,
  `  ADD COLUMN IF NOT EXISTS longitude double precision;`,
  ``,
];

for (const t of terminals) {
  if (t.latitude == null || t.longitude == null) continue;
  terminalLines.push(
    `UPDATE public.cavitour_terminals SET latitude = ${t.latitude}, longitude = ${t.longitude} WHERE terminal_id = ${t.terminal_id};`
  );
}

const estLines = [
  `-- Refresh establishment coordinates in per-LGU places_* tables`,
  `-- Generated by scripts/generate-coordinate-migrations.mjs`,
  ``,
];

const byTable = new Map();
for (const r of establishments) {
  if (r.latitude == null || r.longitude == null || !r.table_name) continue;
  if (!byTable.has(r.table_name)) byTable.set(r.table_name, []);
  byTable.get(r.table_name).push(r);
}

for (const [table, list] of [...byTable.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  estLines.push(`-- ${table} (${list.length})`);
  for (const r of list) {
    estLines.push(
      `UPDATE public.${table} SET latitude = ${r.latitude}, longitude = ${r.longitude} WHERE ta_name = '${esc(r.ta_name)}' AND city_mun = '${esc(r.city_mun)}';`
    );
  }
  estLines.push('');
}

estLines.push(
  `-- Sync public.places from unified view`,
  `INSERT INTO public.places (`,
  `  name, address, type, hours, latitude, longitude, description,`,
  `  ntdp_category, source_slug, type_code, city_mun, updated_at`,
  `)`,
  `SELECT`,
  `  COALESCE(v.name, v.ta_name),`,
  `  v.address,`,
  `  COALESCE(v.ta_category, v.type_code, 'Place'),`,
  `  '',`,
  `  v.latitude::numeric,`,
  `  v.longitude::numeric,`,
  `  v.description,`,
  `  v.ntdp_category,`,
  `  v.id,`,
  `  v.type_code,`,
  `  v.city_mun,`,
  `  NOW()`,
  `FROM public.v_cavite_establishments v`,
  `WHERE v.id IS NOT NULL`,
  `ON CONFLICT (source_slug) DO UPDATE SET`,
  `  latitude = EXCLUDED.latitude,`,
  `  longitude = EXCLUDED.longitude,`,
  `  address = EXCLUDED.address,`,
  `  updated_at = NOW();`,
  ``
);

const migDir = join(root, 'supabase', 'migrations');
writeFileSync(
  join(migDir, `${ts}_terminal_coordinates.sql`),
  terminalLines.join('\n'),
  'utf8'
);
writeFileSync(
  join(migDir, `${ts}_establishment_coordinates.sql`),
  estLines.join('\n'),
  'utf8'
);

const coordMap = Object.fromEntries(
  terminals
    .filter((t) => t.latitude != null)
    .map((t) => [String(t.terminal_id), { latitude: t.latitude, longitude: t.longitude }])
);
writeFileSync(
  join(root, 'apps', 'shared', 'terminalCoordinates.json'),
  JSON.stringify(coordMap, null, 2),
  'utf8'
);

console.log('Wrote migrations:', ts);
console.log('  terminals:', terminals.filter((t) => t.latitude != null).length);
console.log('  establishments:', establishments.filter((r) => r.latitude != null).length);
console.log('  apps/shared/terminalCoordinates.json');
