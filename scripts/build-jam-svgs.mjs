/**
 * Bundles Jam Icons (MIT, https://github.com/michaelampr/jam / iconduck) as TS strings for React Native.
 * Run: node scripts/build-jam-svgs.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.join(__dirname, '..');
const svgDirMobile = path.join(repoRoot, 'apps/mobile/node_modules/jam-icons/svg');
const svgDirHoist = path.join(repoRoot, 'node_modules/jam-icons/svg');
const svgDir = fs.existsSync(svgDirMobile) ? svgDirMobile : svgDirHoist;
const outFile = path.join(repoRoot, 'apps/mobile/lib/jamSvgMap.ts');

const ICONS = [
  'alert',
  'arrow-left',
  'bell',
  'bookmark',
  'book',
  'building',
  'bus',
  'calendar',
  'car',
  'check',
  'chevron-down',
  'chevron-left',
  'chevron-right',
  'chevron-up',
  'circle',
  'clock',
  'close',
  'close-circle',
  'cog',
  'coffee',
  'compass',
  'document',
  'filter',
  'flag',
  'fork',
  'google',
  'heart',
  'home',
  'leaf',
  'log-out',
  'map',
  'map-marker',
  'menu',
  'more-vertical',
  'music',
  'pencil',
  'picture',
  'plus',
  'plus-circle',
  'search',
  'share',
  'shuffle',
  'shopping-bag',
  'smiley',
  'star',
  'train',
  'trash',
  'unordered-list',
  'user',
  'water-drop',
  'world',
];

const entries = [];
for (const name of ICONS) {
  const file = path.join(svgDir, `${name}.svg`);
  if (!fs.existsSync(file)) {
    console.error(`Missing: ${name}.svg`);
    process.exit(1);
  }
  let xml = fs.readFileSync(file, 'utf8').trim();
  xml = xml.replace(/<\?xml[^?]*\?>\s*/i, '');
  xml = xml.replace(/\s+width="[^"]*"/g, '');
  xml = xml.replace(/\s+height="[^"]*"/g, '');
  entries.push(`  '${name}': ${JSON.stringify(xml)},`);
}

const header = `/* Auto-generated by scripts/build-jam-svgs.mjs — Jam Icons MIT */
export const JAM_SVG = {
`;

const footer = `} as const;

export type JamIconName = keyof typeof JAM_SVG;
`;

fs.writeFileSync(outFile, header + '\n' + entries.join('\n') + '\n' + footer, 'utf8');
console.log('Wrote', outFile, `(${ICONS.length} icons)`);
