/**
 * Parse STA-v3 Cavite 2025 Excel → per-LGU JSON + schema/seed stubs.
 *
 * Usage: node scripts/import-sta-cavite-v3.mjs [path/to/STA-v3_CAVITE_2025-1.xlsx]
 */
import XLSX from 'xlsx';
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const DEFAULT_XLSX =
  'c:/Users/Yzeckiel Corpuz/OneDrive/Documents/Emman Docs/ID JUNIORS/STA-v3_CAVITE_2025-1.xlsx';

const EXCLUDE_SHEETS = new Set([
  'Summary',
  'Guide to TA Code',
  'STA2-City',
  'STA2-Prov',
  'Management',
]);

function sheetToTableName(sheetName) {
  const s = sheetName
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .replace(/ñ/gi, 'n')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '');
  return `places_${s || 'unknown'}`;
}

function escSql(s) {
  return String(s ?? '').replace(/'/g, "''");
}

function buildAddress(row) {
  const parts = [row.ta_name, row.barangay, row.city_mun, row.prov_huc, 'Philippines'].filter(Boolean);
  return parts.join(', ');
}

function buildSearchable(row) {
  const parts = [
    row.ta_name,
    row.type_code,
    row.ta_category,
    row.ntdp_category,
    row.city_mun,
    row.barangay,
    row.prov_huc,
    buildAddress(row),
  ]
    .filter(Boolean)
    .join(' ');
  return parts.replace(/\s+/g, ' ').trim().toLowerCase();
}

function buildDescription(row, sheetName) {
  return `NTDP: ${row.ntdp_category || '—'}. Barangay: ${row.barangay || '—'}. STA-v3 Cavite 2025 (${row.city_mun || sheetName}).`;
}

function parseYear(v) {
  if (v === '' || v == null) return null;
  const n = typeof v === 'number' ? v : parseInt(String(v).trim(), 10);
  return Number.isFinite(n) ? n : null;
}

function findHeaderRowIndex(rows) {
  for (let i = 0; i < Math.min(30, rows.length); i++) {
    const r = rows[i];
    if (!r) continue;
    if (String(r[1]).trim() === 'TA_Name' && String(r[0]).trim() === 'No.') return i;
  }
  return 11;
}

function parseSheetRows(sheet) {
  const rows = XLSX.utils.sheet_to_json(sheet, { defval: '', header: 1 });
  const hi = findHeaderRowIndex(rows);
  const out = [];
  for (let i = hi + 1; i < rows.length; i++) {
    const r = rows[i];
    if (!r || r.length < 10) continue;
    const taName = String(r[1] ?? '').trim();
    if (!taName) continue;
    out.push({
      ta_name: taName,
      type_code: String(r[2] ?? '').trim() || null,
      ta_category: String(r[3] ?? '').trim() || null,
      ntdp_category: String(r[4] ?? '').trim() || null,
      year_est: parseYear(r[5]),
      region: String(r[6] ?? '').trim() || null,
      prov_huc: String(r[7] ?? '').trim() || null,
      city_mun: String(r[8] ?? '').trim() || null,
      barangay: String(r[9] ?? '').trim() || null,
    });
  }
  return out;
}

const xlsxPath = process.argv[2] || DEFAULT_XLSX;
const buf = readFileSync(xlsxPath);
const wb = XLSX.read(buf, { type: 'buffer' });

const citySheets = wb.SheetNames.filter((n) => !EXCLUDE_SHEETS.has(n));
const byTable = {};
const flatForGeocode = [];

for (const sheetName of citySheets) {
  const tableName = sheetToTableName(sheetName);
  const rows = parseSheetRows(wb.Sheets[sheetName]);
  byTable[tableName] = { sheetName, rows };
  for (const row of rows) {
    const address = buildAddress(row);
    const searchable_text = buildSearchable(row);
    const description = buildDescription(row, sheetName);
    flatForGeocode.push({
      table_name: tableName,
      sheet_name: sheetName,
      ta_name: row.ta_name,
      type_code: row.type_code,
      ta_category: row.ta_category,
      ntdp_category: row.ntdp_category,
      city_mun: row.city_mun,
      address,
      description,
      searchable_text,
      _row: row,
    });
  }
}

const dataDir = join(root, 'data');
mkdirSync(dataDir, { recursive: true });
const jsonPath = join(dataDir, 'cavite_sta_v3_parsed.json');
writeFileSync(jsonPath, JSON.stringify({ tables: byTable, flat: flatForGeocode }, null, 2), 'utf8');

/* —— SQL: CREATE TABLE per LGU —— */
const ts = new Date()
  .toISOString()
  .replace(/[-:TZ.]/g, '')
  .slice(0, 14);
const migName = `${ts}_cavite_lgu_establishments.sql`;
const migPath = join(root, 'supabase', 'migrations', migName);

const mig = [];
mig.push(`-- STA-v3 Cavite 2025 — per-LGU establishment tables (generated by import-sta-cavite-v3.mjs)`);
mig.push(`CREATE EXTENSION IF NOT EXISTS pg_trgm;`);
mig.push(``);

const tableNames = Object.keys(byTable).sort();

for (const t of tableNames) {
  mig.push(`CREATE TABLE IF NOT EXISTS public.${t} (`);
  mig.push(`  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),`);
  mig.push(`  ta_name TEXT NOT NULL,`);
  mig.push(`  type_code TEXT,`);
  mig.push(`  ta_category TEXT,`);
  mig.push(`  ntdp_category TEXT,`);
  mig.push(`  city_mun TEXT,`);
  mig.push(`  address TEXT NOT NULL,`);
  mig.push(`  latitude DOUBLE PRECISION,`);
  mig.push(`  longitude DOUBLE PRECISION,`);
  mig.push(`  description TEXT,`);
  mig.push(`  searchable_text TEXT NOT NULL,`);
  mig.push(`  search_vector tsvector GENERATED ALWAYS AS (to_tsvector('simple', coalesce(searchable_text, ''))) STORED,`);
  mig.push(`  created_at TIMESTAMPTZ DEFAULT NOW()`);
  mig.push(`);`);
  mig.push(`CREATE INDEX IF NOT EXISTS ${t}_searchable_trgm ON public.${t} USING GIN (searchable_text gin_trgm_ops);`);
  mig.push(`CREATE INDEX IF NOT EXISTS ${t}_search_vec ON public.${t} USING GIN (search_vector);`);
  mig.push(`ALTER TABLE public.${t} ENABLE ROW LEVEL SECURITY;`);
  mig.push(`DROP POLICY IF EXISTS "Public read ${t}" ON public.${t};`);
  mig.push(`CREATE POLICY "Public read ${t}" ON public.${t} FOR SELECT USING (true);`);
  mig.push(`GRANT SELECT ON public.${t} TO anon, authenticated;`);
  mig.push(``);
}

/* Unified view for apps */
const unionParts = tableNames.map(
  (t) =>
    `SELECT id, ta_name AS name, ta_name, type_code, ta_category, ntdp_category, city_mun, address, latitude, longitude, description, searchable_text, created_at, '${escSql(
      t.replace(/^places_/, '')
    )}'::text AS lgu_slug FROM public.${t}`
);
mig.push(`DROP VIEW IF EXISTS public.v_cavite_establishments;`);
mig.push(`CREATE VIEW public.v_cavite_establishments AS`);
mig.push(unionParts.join('\nUNION ALL\n') + ';');
mig.push(``);
mig.push(`ALTER VIEW public.v_cavite_establishments SET (security_invoker = true);`);
mig.push(`GRANT SELECT ON public.v_cavite_establishments TO anon, authenticated;`);
mig.push(``);

writeFileSync(migPath, mig.join('\n'), 'utf8');

